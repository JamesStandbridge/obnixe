import { readFileSync, writeFileSync } from "node:fs";
import { toBase64 } from "../src/agent/encoding.ts";

const source = process.argv[2];
if (source === undefined) throw new Error("Usage: pnpm geoid:generate <path to GeographicLib egm96-15.pgm>");

const file = readFileSync(source);
const tokens: string[] = [];
const comments = new Map<string, string>();
let cursor = 0;
while (tokens.length < 4) {
  const end = file.indexOf(0x0a, cursor);
  const line = file.subarray(cursor, end).toString("latin1").trim();
  cursor = end + 1;
  if (line.startsWith("#")) {
    const [key = "", ...value] = line.slice(1).trim().split(" ");
    comments.set(key, value.join(" "));
  } else tokens.push(...line.split(/\s+/));
}
const [magic, widthText, heightText] = tokens;
if (magic !== "P5") throw new Error(`${source} is not a binary PGM`);
const width = Number(widthText);
const height = Number(heightText);
const sourceOffset = Number(comments.get("Offset"));
const sourceScale = Number(comments.get("Scale"));
const stride = width / 360;
if (!Number.isInteger(stride) || height !== 180 * stride + 1) throw new Error(`Unexpected grid ${width} x ${height}`);

const rows = 181;
const columns = 360;
const grid = new DataView(new ArrayBuffer(rows * columns * 2));
for (let row = 0; row < rows; row += 1) {
  for (let column = 0; column < columns; column += 1) {
    const raw = file.readUInt16BE(cursor + 2 * (row * stride * width + column * stride));
    grid.setInt16(2 * (row * columns + column), Math.round((sourceOffset + sourceScale * raw) * 100), true);
  }
}

const output = new URL("../src/tracking/stages/geoidGrid.ts", import.meta.url);
writeFileSync(
  output,
  `/** EGM96 geoid undulation on a 1 degree grid, generated by \`pnpm geoid:generate\` from GeographicLib ${comments.get("Description") ?? "egm96-15"}: do not edit. */
export const geoidGrid = {
  rows: ${rows},
  columns: ${columns},
  /** Little-endian int16 centimeters, row 0 at 90 N, column 0 at 0 E. */
  centimeters: "${toBase64(new Uint8Array(grid.buffer))}",
} as const;
`,
);
